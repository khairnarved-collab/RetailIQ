"""
Seed the database with demo users and the clearly-labelled SYNTHETIC sample data.

    cd backend
    alembic upgrade head          # create the tables
    python -m scripts.seed        # load sample data + demo accounts

Options:
    --m5-dir PATH    load the REAL M5 files from PATH instead of the synthetic sample
    --stores ...     (with --m5-dir) comma-separated store subset, e.g. CA_1,TX_1,WI_1
    --max-items N    (with --m5-dir) random subset of N items
    --start-date     (with --m5-dir) e.g. 2015-01-01
    --reset          delete existing sales data first
"""
from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

from sqlalchemy import delete, func, select

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.core.config import settings  # noqa: E402
from app.core.logging import setup_logging  # noqa: E402
from app.core.security import hash_password  # noqa: E402
from app.database.session import SessionLocal  # noqa: E402
from app.models import (  # noqa: E402
    DataQualityReport,
    Dataset,
    Notification,
    Role,
    Sale,
    User,
)
from app.services import data_quality as dq  # noqa: E402
from app.services import sample_data  # noqa: E402
from app.services.dataset_import import import_customer_transactions  # noqa: E402
from app.services.m5_ingestion import IngestOptions, load_m5  # noqa: E402

DEMO_USERS = [
    ("admin@retailiq.dev", "Avery Admin", "Admin@12345", Role.ADMIN, "Head of Analytics"),
    ("analyst@retailiq.dev", "Riya Analyst", "Analyst@12345", Role.ANALYST, "Business Analyst"),
]


def ensure_sample_files() -> Path:
    m5_dir = settings.SAMPLE_DIR / "m5_synthetic"
    if not (m5_dir / "sales_train_synthetic.csv").exists():
        print("Generating synthetic sample data ...")
        sample_data.generate(m5_dir)
    if not (settings.SAMPLE_DIR / "customer_transactions_synthetic.csv").exists():
        sample_data.generate_customers(settings.SAMPLE_DIR / "customer_transactions_synthetic.csv")
    if not (settings.SAMPLE_DIR / "messy_sales_sample.csv").exists():
        sample_data.generate_messy_sales(settings.SAMPLE_DIR / "messy_sales_sample.csv")
    return m5_dir


def seed_users(db) -> None:
    for email, name, pw, role, title in DEMO_USERS:
        if not db.scalar(select(User).where(User.email == email)):
            db.add(User(email=email, full_name=name, hashed_password=hash_password(pw), role=role, job_title=title))
            print(f"  created demo user {email}")
    db.commit()


def seed_customers(db, admin_id: int | None) -> None:
    src = settings.SAMPLE_DIR / "customer_transactions_synthetic.csv"
    if db.scalar(select(func.count(Dataset.id)).where(Dataset.kind == "customer_transactions")):
        return
    stored = settings.UPLOAD_DIR / "sample_customer_transactions_synthetic.csv"
    shutil.copyfile(src, stored)
    df = dq.read_table(stored)
    ds = Dataset(name="Customer transactions (SYNTHETIC sample)", original_filename=src.name,
                 kind="customer_transactions", file_path=str(stored), n_rows=len(df), n_cols=df.shape[1],
                 status="profiled", is_synthetic=True, uploaded_by=admin_id,
                 description="SYNTHETIC customer transactions generated by RetailIQ for demonstrating the "
                             "customer-analytics module. It is independent of the M5 data (M5 has no customer data).")
    db.add(ds)
    db.flush()
    db.add(DataQualityReport(dataset_id=ds.id, stage="raw", report=dq.profile(df)))
    res = dq.clean(df, "customer_transactions")
    cleaned = settings.PROCESSED_DIR / f"dataset_{ds.id}_cleaned.csv"
    rejected = settings.PROCESSED_DIR / f"dataset_{ds.id}_rejected.csv"
    res.cleaned.to_csv(cleaned, index=False, date_format="%Y-%m-%d")
    res.rejected.to_csv(rejected, index=False)
    ds.cleaned_path, ds.rejected_path = str(cleaned), str(rejected)
    db.add(DataQualityReport(dataset_id=ds.id, stage="cleaning", report=res.summary()))
    db.add(DataQualityReport(dataset_id=ds.id, stage="cleaned", report=dq.profile(res.cleaned)))
    import pandas as pd
    n = import_customer_transactions(db, ds, pd.read_csv(cleaned))
    ds.status, ds.imported_rows = "imported", n
    db.commit()
    print(f"  imported {n:,} synthetic customer transactions")


def main() -> None:
    setup_logging()
    ap = argparse.ArgumentParser()
    ap.add_argument("--m5-dir", type=Path)
    ap.add_argument("--stores")
    ap.add_argument("--max-items", type=int)
    ap.add_argument("--start-date")
    ap.add_argument("--reset", action="store_true")
    a = ap.parse_args()

    with SessionLocal() as db:
        print("Seeding demo users ...")
        seed_users(db)
        admin = db.scalar(select(User).where(User.email == DEMO_USERS[0][0]))

        if a.reset:
            db.execute(delete(Sale))
            db.commit()
        has_sales = db.scalar(select(func.count(Sale.id))) or 0
        if has_sales and not a.m5_dir:
            print(f"Sales data already present ({has_sales:,} rows) - skipping sales load (use --reset to reload).")
        else:
            if a.m5_dir:
                opts = IngestOptions(data_dir=a.m5_dir, stores=a.stores.split(",") if a.stores else None,
                                     max_items=a.max_items, start_date=a.start_date)
                print(f"Loading REAL M5 data from {a.m5_dir} ...")
            else:
                opts = IngestOptions(data_dir=ensure_sample_files())
                print("Loading SYNTHETIC M5-format sample data ...")
            res = load_m5(db, opts, uploaded_by=admin.id if admin else None)
            print(f"  {res.sales_rows:,} sales rows, {res.products} products, {res.stores} stores")

        ensure_sample_files()
        print("Loading synthetic customer dataset ...")
        seed_customers(db, admin.id if admin else None)

        for u in db.scalars(select(User)).all():
            if not db.scalar(select(func.count(Notification.id)).where(Notification.user_id == u.id)):
                db.add(Notification(user_id=u.id, level="info", title="Welcome to RetailIQ",
                                    message="The workspace is loaded with a SYNTHETIC demo dataset in M5 format. "
                                            "Upload your own data from Data Management.", link="/app/data"))
        db.commit()
    print("Done.")


if __name__ == "__main__":
    main()
